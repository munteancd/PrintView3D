"""Create the demo files in examples/ (a twisted gear vase as STL, 3MF and G-code).

They are used for the README screenshots and are handy for trying PrintView3D.
The G-code is produced by a tiny built-in "slicer" for this one shape: walls,
infill, top/bottom layers and a skirt, written with Creality Print / Orca-style
comments so all feature colours show up.

Run:  python tools/make_demo.py
"""

from __future__ import annotations

import base64
import math
import os
import struct
import zipfile


def _fixed_writestr(z, name, data):
    """Write a zip member with a fixed timestamp so regenerated files are identical."""
    info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    z.writestr(info, data)
import zlib

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "examples")

# Shape parameters (mm)
CX, CY = 175.0, 175.0          # centre on a 350 x 350 bed (Creality K2 Plus)
R, LOBES, AMP = 26.0, 9, 3.2    # base radius, number of lobes, lobe depth
HEIGHT, TWIST = 70.0, 80.0      # height, total twist in degrees
BULGE = 6.0                     # extra radius halfway up
LAYER = 0.2
NOZZLE = 0.42


def radius(theta, z):
    t = z / HEIGHT
    return R + BULGE * math.sin(math.pi * t) + AMP * math.cos(LOBES * (theta - math.radians(TWIST) * t))


def outline(z, inset=0.0, n=360):
    th = np.linspace(0, 2 * math.pi, n, endpoint=False)
    r = np.array([radius(a, z) for a in th]) - inset
    return np.column_stack([CX + r * np.cos(th), CY + r * np.sin(th)])


# --------------------------------------------------------------------- mesh
def make_mesh(n_th=216, n_z=140):
    zs = np.linspace(0, HEIGHT, n_z)
    rings = [np.column_stack([outline(z, n=n_th), np.full(n_th, z)]) for z in zs]
    verts = np.vstack(rings + [[(CX, CY, 0.0)], [(CX, CY, HEIGHT)]])
    bottom_c, top_c = len(verts) - 2, len(verts) - 1
    faces = []
    for k in range(n_z - 1):
        for i in range(n_th):
            a = k * n_th + i
            b = k * n_th + (i + 1) % n_th
            c = (k + 1) * n_th + (i + 1) % n_th
            d = (k + 1) * n_th + i
            faces += [(a, b, c), (a, c, d)]
    for i in range(n_th):
        faces.append((bottom_c, (i + 1) % n_th, i))
        top0 = (n_z - 1) * n_th
        faces.append((top_c, top0 + i, top0 + (i + 1) % n_th))
    return verts.astype(np.float32), np.array(faces, dtype=np.int64)


def write_stl(path, verts, faces, name=b"PrintView3D demo vase"):
    with open(path, "wb") as f:
        f.write(name.ljust(80, b"\0"))
        f.write(struct.pack("<I", len(faces)))
        for a, b, c in faces:
            f.write(struct.pack("<3f", 0, 0, 0))
            for i in (a, b, c):
                f.write(struct.pack("<3f", *verts[i]))
            f.write(b"\0\0")


# -------------------------------------------------------------------- gcode
def scan_infill(poly, spacing, angle_deg):
    """Parallel lines at angle, clipped to polygon (even-odd)."""
    a = math.radians(angle_deg)
    ca, sa = math.cos(a), math.sin(a)
    rot = poly @ np.array([[ca, -sa], [sa, ca]])          # rotate by -angle
    ys = np.arange(rot[:, 1].min() + spacing / 2, rot[:, 1].max(), spacing)
    p0, p1 = rot, np.roll(rot, -1, axis=0)
    lines = []
    for j, y in enumerate(ys):
        cross = ((p0[:, 1] <= y) & (p1[:, 1] > y)) | ((p1[:, 1] <= y) & (p0[:, 1] > y))
        t = (y - p0[cross, 1]) / (p1[cross, 1] - p0[cross, 1])
        xs = np.sort(p0[cross, 0] + t * (p1[cross, 0] - p0[cross, 0]))
        segs = [(xs[i], xs[i + 1]) for i in range(0, len(xs) - 1, 2)]
        if j % 2:
            segs = [(b, a_) for a_, b in reversed(segs)]
        for xa, xb in segs:
            pts = np.array([[xa, y], [xb, y]]) @ np.array([[ca, sa], [-sa, ca]])
            lines.append(pts)
    return lines


def make_gcode(thumb_png: bytes) -> str:
    out = []
    w = out.append
    e_per_mm = (NOZZLE * LAYER) / (math.pi * (1.75 / 2) ** 2)
    total_e = 0.0

    def ext(p, q):
        nonlocal total_e
        d = math.dist(p, q) * e_per_mm
        total_e += d
        return d

    w("; HEADER_BLOCK_START")
    w("; generated by PrintView3D demo generator")
    w("; HEADER_BLOCK_END")
    b64 = base64.b64encode(thumb_png).decode()
    w(f"; thumbnail begin 300x300 {len(b64)}")
    for i in range(0, len(b64), 78):
        w("; " + b64[i:i + 78])
    w("; thumbnail end")
    w("G28\nG90\nM83\nM104 S210\nM140 S60")
    n_layers = int(round(HEIGHT / LAYER))
    for L in range(n_layers):
        z = (L + 1) * LAYER
        w(";LAYER_CHANGE")
        w(f";Z:{z:.2f}")
        w(f"G1 Z{z:.2f} F600")
        if L == 0:
            w(";TYPE:Skirt")
            sk = outline(z, inset=-6.0, n=180)
            w(f"G1 X{sk[0,0]:.3f} Y{sk[0,1]:.3f} F9000")
            for p, q in zip(sk, np.roll(sk, -1, axis=0)):
                w(f"G1 X{q[0]:.3f} Y{q[1]:.3f} E{ext(p, q):.5f} F1800")
        walls = [("Outer wall", NOZZLE / 2), ("Inner wall", NOZZLE * 1.5), ("Inner wall", NOZZLE * 2.5)]
        for name, inset in reversed(walls):
            poly = outline(z, inset=inset, n=180)
            w(f";TYPE:{name}")
            w(f"G1 X{poly[0,0]:.3f} Y{poly[0,1]:.3f} F9000")
            speed = 3000 if name == "Outer wall" else 6000
            for p, q in zip(poly, np.roll(poly, -1, axis=0)):
                w(f"G1 X{q[0]:.3f} Y{q[1]:.3f} E{ext(p, q):.5f} F{speed}")
        inner = outline(z, inset=NOZZLE * 3.2, n=180)
        if L < 4:
            kind, spacing = "Bottom surface", NOZZLE
        elif L >= n_layers - 4:
            kind, spacing = "Top surface", NOZZLE
        elif L in (4, 5, n_layers - 6, n_layers - 5):
            kind, spacing = "Internal solid infill", NOZZLE
        else:
            kind, spacing = "Sparse infill", 4.0
        angle = 45 if L % 2 == 0 else -45
        w(f";TYPE:{kind}")
        for seg in scan_infill(inner, spacing, angle):
            w(f"G1 X{seg[0,0]:.3f} Y{seg[0,1]:.3f} F12000")
            w(f"G1 X{seg[1,0]:.3f} Y{seg[1,1]:.3f} E{ext(seg[0], seg[1]):.5f} F7000")
    grams = total_e * math.pi * (1.75 / 2) ** 2 * 1.24 / 1000
    w("M104 S0\nM140 S0\nG1 Z{:.2f} F600".format(HEIGHT + 10))
    w(f"; filament used [mm] = {total_e:.2f}")
    w(f"; filament used [g] = {grams:.2f}")
    w("; estimated printing time (normal mode) = 2h 14m 37s")
    w("; filament_type = PLA")
    w("; layer_height = 0.2")
    w("; nozzle_diameter = 0.4")
    w("; printer_model = Creality K2 Plus")
    w("; printable_area = 0x0,350x0,350x350,0x350")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------- 3mf
def write_3mf(path, parts, thumb_png):
    core = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"

    def mesh_xml(v, f):
        vs = "".join(f'<vertex x="{x:.4f}" y="{y:.4f}" z="{z:.4f}"/>' for x, y, z in v)
        ts = "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in f)
        return f"<mesh><vertices>{vs}</vertices><triangles>{ts}</triangles></mesh>"

    objs = "".join(f'<object id="{i+1}" name="{name}" type="model">{mesh_xml(v, f)}</object>'
                   for i, (name, v, f) in enumerate(parts))
    items = "".join(f'<item objectid="{i+1}"/>' for i in range(len(parts)))
    model = (f'<?xml version="1.0" encoding="UTF-8"?>\n<model unit="millimeter" xmlns="{core}">'
             f'<metadata name="Application">PrintView3D demo</metadata>'
             f'<resources>{objs}</resources><build>{items}</build></model>')
    rels = ('<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Target="/3D/3dmodel.model" Id="rel0" '
            'Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
    cfg = ('{"printer_model": "Creality K2 Plus", "layer_height": "0.2", "nozzle_diameter": ["0.4"], '
           '"filament_type": ["PLA"], "printable_area": ["0x0","350x0","350x350","0x350"]}')
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        _fixed_writestr(z, "[Content_Types].xml", '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>')
        _fixed_writestr(z, "_rels/.rels", rels)
        _fixed_writestr(z, "3D/3dmodel.model", model)
        _fixed_writestr(z, "Metadata/project_settings.config", cfg)
        _fixed_writestr(z, "Metadata/plate_1.png", thumb_png)


def box(cx, cy, sx, sy, sz):
    v = np.array([(x, y, z) for z in (0, sz) for y in (cy - sy / 2, cy + sy / 2) for x in (cx - sx / 2, cx + sx / 2)],
                 dtype=np.float32)
    f = [(0, 2, 3), (0, 3, 1), (4, 5, 7), (4, 7, 6), (0, 1, 5), (0, 5, 4),
         (1, 3, 7), (1, 7, 5), (3, 2, 6), (3, 6, 7), (2, 0, 4), (2, 4, 6)]
    return v, np.array(f)


def cylinder(cx, cy, r, h, n=96):
    th = np.linspace(0, 2 * math.pi, n, endpoint=False)
    ring = np.column_stack([cx + r * np.cos(th), cy + r * np.sin(th)])
    v = np.vstack([np.column_stack([ring, np.zeros(n)]), np.column_stack([ring, np.full(n, h)]),
                   [(cx, cy, 0)], [(cx, cy, h)]]).astype(np.float32)
    f = []
    for i in range(n):
        j = (i + 1) % n
        f += [(i, j, n + j), (i, n + j, n + i), (2 * n, j, i), (2 * n + 1, n + i, n + j)]
    return v, np.array(f)


def tiny_png(color=(47, 164, 160), size=64):
    raw = b"".join(b"\x00" + bytes(color) * size for _ in range(size))

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def main(thumb_png: bytes | None = None):
    os.makedirs(OUT, exist_ok=True)
    thumb = thumb_png or tiny_png()
    v, f = make_mesh()
    write_stl(os.path.join(OUT, "demo_vase.stl"), v, f)
    with open(os.path.join(OUT, "demo_vase.gcode"), "w") as fh:
        fh.write(make_gcode(thumb))
    # 3MF plate: vase + two small objects
    v_small, f_small = make_mesh(n_th=96, n_z=60)
    v_small = (v_small - [CX, CY, 0]) * [0.55, 0.55, 0.55] + [CX + 75, CY + 10, 0]
    bv, bf = box(CX - 70, CY - 20, 30, 30, 18)
    cv, cf = cylinder(CX - 65, CY + 45, 14, 32)
    write_3mf(os.path.join(OUT, "demo_plate.3mf"),
              [("Gear vase", v, f), ("Mini vase", v_small.astype(np.float32), f_small),
               ("Calibration cube", bv, bf), ("Spool holder pin", cv, cf)], thumb)
    print("Demo files written to", OUT)


if __name__ == "__main__":
    main()
